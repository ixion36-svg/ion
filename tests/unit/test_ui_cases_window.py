"""The opened case's two layouts: what the view model derives for them.

Triage and Read show the same case, so everything they say beyond the
case payload is derived once, in ui/_cases_window.py, from rows ION
already has: Bob's notes and investigations, the triage suggestions,
the stored enrichments. Each test names the wrong answer it guards
against, because most of them are the difference between "unknown",
"none" and data.
"""
from __future__ import annotations

import json

from ion.web.ui._cases_window import (
    alert_bob,
    blockers,
    bob_case_note,
    bob_text,
    letter,
    observable_cards,
    summary_view,
)
from ion.web.ui.cases import panel_observables, panel_view

MARKER = "**\U0001F916 Bob (AI analyst) — `%s`** · severity `low` · confidence `low`"


# ── Bob's prose: the fenced-JSON parse failure ──────────────────────────


def test_a_fenced_json_reply_reads_as_its_summary():
    """CASE-0118's note: the model's envelope stored as a ```json block."""
    raw = "\n\n```json\n" + json.dumps({"verdict": "true_positive",
                                        "summary": "Bulk credential read."}) + "\n```"
    assert bob_text(raw) == "Bulk credential read."


def test_a_fenced_block_inside_prose_is_replaced_in_place():
    raw = "Intro.\n```json\n{\"summary\": \"Bulk read.\", \"verdict\": \"x\"}\n```\n_Auto-generated by Bob._"
    assert bob_text(raw) == "Intro.\nBulk read.\n_Auto-generated by Bob._"


def test_a_fenced_block_that_does_not_parse_keeps_its_text_without_fences():
    raw = "Before.\n```json\n{\"summary\": \"cut off mid\n```\nAfter."
    text = bob_text(raw)
    assert "```" not in text
    assert '"summary": "cut off mid' in text
    assert text.startswith("Before.") and text.endswith("After.")


def test_a_reply_cut_off_mid_json_still_reads_as_its_summary():
    """CASE-0118: the envelope stops partway through key_observations, so it
    does not parse, but the summary before the cut is whole."""
    raw = ('```json\n{\n  "verdict": "true_positive",\n  "summary": "Bulk credential read '
           'from an \\"unknown\\" host.",\n  "key_observations": [{"field": "sha256", "value": "2562')
    assert bob_text(raw) == 'Bulk credential read from an "unknown" host.'


def test_a_fence_that_never_closes_is_still_unwrapped():
    raw = "```json\n" + json.dumps({"summary": "Truncated reply."})
    assert bob_text(raw) == "Truncated reply."


def test_parsed_json_without_a_summary_is_shown_as_text_not_dropped():
    raw = "```json\n{\"verdict\": \"benign\"}\n```"
    assert bob_text(raw) == '{"verdict": "benign"}'


def test_bob_text_of_nothing_is_none_not_an_empty_string():
    assert bob_text(None) is None
    assert bob_text("   ") is None


def test_the_latest_bob_case_note_wins_and_others_are_ignored():
    notes = [
        {"content": MARKER % "benign" + "\n\nolder", "created_at": "2026-10-01T00:00:00"},
        {"content": "an analyst note", "created_at": "2026-10-03T00:00:00"},
        {"content": MARKER % "true_positive" + "\n\nnewer", "created_at": "2026-10-02T00:00:00"},
    ]
    note = bob_case_note(notes)
    assert note["verdict"] == "true_positive"
    assert note["text"] == "newer"
    assert "confidence `low`" in note["headline"]


def test_a_case_without_a_bob_note_has_none():
    assert bob_case_note([{"content": "just us"}]) is None
    assert bob_case_note(None) is None


# ── The Read summary names its source ───────────────────────────────────


def test_the_summary_prefers_bob_then_evidence_then_description():
    note = {"verdict": "benign", "headline": "", "text": "Bob says.", "when": None}
    assert summary_view(note, "evidence", "desc")["source"] == "bob_note"
    assert summary_view(None, "evidence", "desc")["source"] == "evidence_summary"
    view = summary_view(None, "  ", "**Auto-grouped case** — clustered")
    assert view["source"] == "description"
    assert view["label"] == "The case grouper's templated description"
    assert summary_view(None, None, "Written by hand")["label"] == "The case description"


def test_no_summary_source_says_so():
    view = summary_view(None, None, None)
    assert view["source"] == "none" and view["text"] is None


# ── Bob on one alert ────────────────────────────────────────────────────


def test_an_investigation_is_shown_with_its_fenced_summary_unwrapped():
    extras = {"investigations": {"a1": {
        "status": "completed", "verdict": "true_positive", "confidence_int": 80,
        "summary_text": "```json\n{\"summary\": \"Beaconing.\"}\n```",
        "recommended_actions_json": json.dumps([{"action": "Isolate"}, "Reset"])}},
        "triage": {"a1": {"suggested_verdict": "true_positive", "suggested_confidence": "high",
                          "badge": "low_confidence_triage"}}}
    bob = alert_bob("a1", extras)
    assert bob["state"] == "investigated"
    assert bob["summary"] == "Beaconing."
    assert bob["actions"] == ["Isolate", "Reset"]
    assert bob["badge"] == "low_confidence_triage"


def test_no_investigation_is_none_and_a_failed_read_is_unknown():
    """Three answers: Bob looked, Bob did not, we could not tell."""
    assert alert_bob("a1", {"investigations": {}, "triage": {}})["state"] == "none"
    assert alert_bob("a1", {"investigations": None, "triage": None})["state"] == "unknown"
    assert alert_bob("a1", None)["state"] == "unknown"


