# ── Observables: enrichment by source, and the empty states ─────────────


def test_an_observable_names_the_alerts_that_carry_it_by_letter():
    alerts = [{"es_alert_id": "x", "observables": [{"type": "source_ip", "value": "1.2.3.4"}]},
              {"es_alert_id": "y", "observables": [{"type": "source_ip", "value": "1.2.3.4"}]}]
    chips = panel_observables([], alerts, {"x": "A", "y": "B"})
    assert chips[0]["letters"] == ["A", "B"]
    assert chips[0]["alert_ids"] == ["x", "y"]


def test_the_inline_opencti_result_becomes_a_source_card():
    """CASE-0003's source IP: triage stored OpenCTI's answer on it."""
    alerts = [{"es_alert_id": "x", "observables": [
        {"type": "source_ip", "value": "23.106.215.76", "enriched": True, "threat_labels": [],
         "threat_actors": [], "indicator_count": 1, "score": 80}]}]
    cards = observable_cards(panel_observables([], alerts, {"x": "A"}),
                             {"enrichments": {}})
    src = cards[0]["sources"]
    assert [s["name"] for s in src] == ["OpenCTI"]
    assert ("Score", "80 / 100") in src[0]["rows"]
    assert ("Labels", "none") in src[0]["rows"]
    assert cards[0]["lookup_type"] == "ip"


def test_an_unenriched_observable_has_no_sources_and_a_known_store():
    cards = observable_cards(panel_observables([{"type": "hostname", "value": "WS-1"}], []),
                             {"enrichments": {}})
    assert cards[0]["sources"] == []
    assert cards[0]["stored_unknown"] is False
    assert cards[0]["lookup_type"] is None


def test_a_failed_enrichment_read_is_unknown_not_none():
    cards = observable_cards(panel_observables([{"type": "ip", "value": "9.9.9.9"}], []),
                             {"enrichments": None})
    assert cards[0]["stored_unknown"] is True


def test_stored_enrichments_are_matched_by_value_case_insensitively():
    row = {"source": "opencti", "enriched_at": None, "is_malicious": True, "score": 90,
           "labels": ["c2"], "threat_actors": [], "indicators": [1, 2]}
    cards = observable_cards(panel_observables([{"type": "domain", "value": "Evil.TEST"}], []),
                             {"enrichments": {"evil.test": [row]}})
    rows = dict(cards[0]["sources"][0]["rows"])
    assert rows["Verdict"] == "malicious" and rows["Indicators"] == "2"


def test_a_retention_marker_row_is_not_an_alert_of_the_case():
    """CASE-0003 and CASE-0044 carry `retention:<id>` triage rows, filed by
    the Arkime retention job to warn once. Listed as alerts they were
    exhibits with no document and a blocker that could never clear."""
    view = panel_view({"id": 3, "severity": "critical", "assigned_to_id": 1, "alerts": [
        {"es_alert_id": "retention:3", "status": "open", "observables": []},
        {"es_alert_id": "real", "status": "closed", "observables": []}],
        "observables": [], "notes": []}, [], False,
        {"investigations": {}, "triage": {}, "enrichments": {}})
    assert [a["alert_id"] for a in view["alerts"]] == ["real"]
    assert view["alert_count"] == 1
    assert view["blockers"] == []


# ── The rail's exhibit letters ──────────────────────────────────────────


def test_letters_run_past_z():
    assert [letter(i) for i in (0, 25, 26, 27)] == ["A", "Z", "AA", "AB"]


def test_panel_view_letters_alerts_in_rail_order_and_attaches_bob():
    view = panel_view({"id": 1, "severity": "high", "alerts": [
        {"es_alert_id": "low", "priority": "low", "observables": []},
        {"es_alert_id": "crit", "priority": "critical", "observables": []}],
        "observables": [], "notes": []}, [], False,
        {"investigations": {}, "triage": {}, "enrichments": {}})
    assert [(a["alert_id"], a["letter"]) for a in view["alerts"]] == [("crit", "A"), ("low", "B")]
    assert view["alerts"][0]["bob"]["state"] == "none"
