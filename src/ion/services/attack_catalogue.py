"""The ATT&CK Enterprise technique catalogue ION ships, for coverage figures.

TIDE 6 moved its technique table into a reference database that its
external query API refuses to read, so coverage can no longer ask TIDE what
the techniques are. ION carries the same catalogue in
``data/attack_techniques.json`` (generated by
``scripts/generate_attack_techniques_json.py``), and this reads it.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

_PATH = Path(__file__).resolve().parents[1] / "data" / "attack_techniques.json"

# Enterprise tactics in kill-chain order, named as the bundled catalogue's
# ATT&CK release names them: it splits Defense Evasion into Stealth (TA0005)
# and Defense Impairment (TA0112).
TACTIC_NAMES = {
    "TA0043": "Reconnaissance",
    "TA0042": "Resource Development",
    "TA0001": "Initial Access",
    "TA0002": "Execution",
    "TA0003": "Persistence",
    "TA0004": "Privilege Escalation",
    "TA0005": "Stealth",
    "TA0112": "Defense Impairment",
    "TA0006": "Credential Access",
    "TA0007": "Discovery",
    "TA0008": "Lateral Movement",
    "TA0009": "Collection",
    "TA0011": "Command and Control",
    "TA0010": "Exfiltration",
    "TA0040": "Impact",
}


@lru_cache(maxsize=1)
def techniques() -> tuple[dict, ...]:
    """Every technique as ``{technique_id, name, tactic}``, sorted by id.

    ``tactic`` is the name of the technique's first tactic, the label the
    coverage views group by; None when the catalogue gives no tactic.
    """
    rows = []
    for entry in json.loads(_PATH.read_text(encoding="utf-8")):
        tactic_ids = entry.get("tactic_ids") or []
        rows.append({
            "technique_id": entry["id"],
            "name": entry.get("name"),
            "tactic": TACTIC_NAMES.get(tactic_ids[0]) if tactic_ids else None,
        })
    return tuple(sorted(rows, key=lambda r: r["technique_id"]))
