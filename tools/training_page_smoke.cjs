const {chromium} = require(process.env.PLAYWRIGHT_NODE_MODULES ? require('node:path').join(process.env.PLAYWRIGHT_NODE_MODULES, 'playwright') : 'playwright');
const fs = require('fs');
(async () => {
  const options = {headless:true};
  if (process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE) options.executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE;
  const browser = await chromium.launch(options);
  const base = process.env.ION_SMOKE_BASE_URL || 'http://127.0.0.1:8819';
  const passwordFile = process.env.ION_SMOKE_PASSWORD_FILE || process.argv[2];
  if (!passwordFile) throw new Error('Provide ION_SMOKE_PASSWORD_FILE or a password file argument.');
  fs.mkdirSync('.audit', {recursive:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base + '/login');
  await page.locator('#username').fill(process.env.ION_SMOKE_USERNAME || 'admin');
  await page.locator('#password').fill(fs.readFileSync(passwordFile,'utf8').trim());
  await page.locator('button[type=submit]').click();
  await page.waitForURL(url => !url.pathname.includes('login'));
  await page.goto(base + '/training');
  await page.waitForLoadState('networkidle');
  console.log(JSON.stringify({title:await page.title(),tabs:await page.locator('[data-click-action="switchTab"]').allTextContents(),cards:await page.locator('.role-card').count(),errors}));
  await page.screenshot({path:'.audit/training-before.png', fullPage:true});
  await page.evaluate(() => {
    Object.defineProperty(Element.prototype,'innerHTML',{set(){throw new Error('HTML string write prohibited');}});
    document.querySelector('.role-card').click();
  });
  await page.waitForTimeout(100);
  const title = await page.locator('#detail-content .detail-title').textContent({timeout:2000});
  if (!title) throw new Error('role detail did not render');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Role detail works with HTML string writes prohibited.');
  await page.evaluate(() => {
    switchCertFilter('cs');
    switchMode('from');
    showRoleDetail('soc-lead');
    modShowDetail(Object.keys(MOD_ROLES)[0]);
    closeDetail();
    switchTab('tab-assessment');
    careerGoal.target_role = 'soc-lead';
    renderAssessmentForm();
    reviewCycle={submitted_at:'2026-07-01',next_review_at:'2026-10-01',is_overdue:true};
    renderReviewBanner();
  });
  if (!(await page.locator('#sa-form .sa-rating-btn').count())) throw new Error('No rating controls');
  await page.locator('#sa-form .sa-rating-btn').first().click();
  if (!(await page.locator('#sa-form .sa-rating-btn.selected').count())) throw new Error('Rating did not select');
  if (await page.locator('#sa-review-banner strong').textContent() !== 'Review Overdue') throw new Error('Missing review state');
  await page.evaluate(() => {
    reviewCycle={is_locked:true,days_until_review:0};renderReviewBanner();
    if (!document.getElementById('sa-review-banner').textContent.includes('0 days')) throw new Error('Measured zero review lost');
    reviewCycle={is_locked:false};renderReviewBanner();
    crInit();crShowDetail(CR_CERTS[0].id);
  });
  if (!(await page.locator('#cr-detail-panel').textContent()).trim()) throw new Error('Missing certificate detail');
  await page.evaluate(async () => {
    await rmShowRolePicker();
    if (rmDefinitions.roles.length) rmStartAssessment(rmDefinitions.roles[0].id);
  });
  if (!(await page.locator('#rm-content').textContent()).trim()) throw new Error('Missing role matching state');
  await page.evaluate(() => switchTab('tab-myplan'));
  await page.locator('[data-click-action="tpShowCreateModal"]').first().click();
  if (!(await page.locator('#tp-new-roles-multi').textContent()).trim()) throw new Error('No plan roles');
  await page.evaluate(() => {tpHideCreateModal();switchTab('tab-team');});
  if (!(await page.locator('#tab-team-btn').isVisible())) throw new Error('Authorized Team tab hidden');
  await page.evaluate(() => switchTab('tab-schedule'));
  await page.waitForTimeout(250);
  const args = await page.locator('[data-args]').evaluateAll(elements => elements.map(el=>{try {JSON.parse(el.dataset.args);return null;}catch {return el.outerHTML;}}).filter(Boolean));
  if (args.length) throw new Error('Invalid delegated JSON: ' + args.join('\n'));
  if (errors.length) throw new Error(errors.join('\n'));
  await page.screenshot({path:'.audit/training-after-dark.png',fullPage:true});
  await page.evaluate(() => document.documentElement.setAttribute('data-mode','light'));
  await page.waitForTimeout(300);
  await page.screenshot({path:'.audit/training-after-light.png',fullPage:true});
  console.log('Integrated role, skills, reviews, career, matching, plan modal, team and schedule controls passed.');
  await browser.close();
})().catch(e=>{ console.error(e); process.exit(1); });
